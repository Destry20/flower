// Первый, самый дешёвый уровень модерации новых открыток и подписей под
// общими открытками: не блокирует создание (ложное срабатывание на
// безобидный текст не должно портить человеку подарок), только ставит флаг —
// в админке (Preview у обычных открыток, сама страница /group/:id у общих)
// уже можно быстро посмотреть, что там на самом деле написано, вместо того
// чтобы листать всё подряд вручную. Разбор целиком локальный — ничего никуда
// не отправляется.
//
// Специально узкий охват: структурные паттерны (ссылка/телефон/крипто-адрес —
// типичный вектор спама/мошенничества через "подарочную" ссылку) и явные
// конструкции угрозы/самоповреждения. Осознанно НЕ пытается ловить
// оскорбления/разжигание ненависти словарём — список слов на естественном
// языке легко обходится (пробелы, замена букв) и даёт либо море ложных
// срабатываний на безобидный текст, либо ложное чувство защищённости. Если
// этого уровня окажется мало, следующий шаг — проверка через Claude (см.
// обсуждение с пользователем), которая понимает контекст, а не просто ищет
// подстроки.

const URL_RE = /https?:\/\/\S+|(?:^|[\s(])(?:www\.)?[a-z0-9-]+\.(?:com|net|org|ru|io|xyz|top|click|link|info|biz|site|me)(?:[/\s)]|$)/i;
const PHONE_RE = /(?:\+?\d[\d\-\s()]{8,}\d)/;
const CRYPTO_RE = /\b(?:0x[a-fA-F0-9]{40}|bc1[a-z0-9]{25,39}|[13][a-km-zA-HJ-NP-Z1-9]{25,34})\b/;

// Готовые фразы-конструкции, а не отдельные слова: "убью тебя" — однозначный
// сигнал, а голое "убить" естественно встречается в массе безобидных
// контекстов (шутки, кино, "убить время") и только шумело бы.
const THREAT_RE = /убью тебя|тебя убью|прибью тебя|я тебя найду и|зарежу тебя|прикончу тебя|i(?:'| a)?ll kill you|i will kill you|going to kill you|you('| a)?re going to die|kill yourself|go kill yourself|\bkys\b/iu;

function scanText(text){
  if(typeof text !== 'string' || !text) return [];
  const reasons = [];
  if(URL_RE.test(text)) reasons.push('link');
  if(PHONE_RE.test(text)) reasons.push('phone');
  if(CRYPTO_RE.test(text)) reasons.push('crypto_address');
  if(THREAT_RE.test(text)) reasons.push('threat');
  return reasons;
}

// to/from/message — три поля, которые реально попадают в готовую открытку
// или подпись под общей открыткой. Возвращает объединённый список причин без
// повторов (одна и та же причина в двух полях не должна давать два одинаковых
// тега в админке).
function scanCard({ to, from, message }){
  const reasons = new Set([...scanText(to), ...scanText(from), ...scanText(message)]);
  return { flagged: reasons.size > 0, flagReasons: Array.from(reasons) };
}

module.exports = { scanText, scanCard };
